#!/usr/bin/env python3
"""Export the assets the C++ runtime needs: tokenizer.bin + split codec .npy.

    python export/export_cpp_assets.py [--out sdk/assets]
"""

from __future__ import annotations

import argparse
import json
import struct
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def write_tokenizer(path, tok_json):
    vocab = tok_json["model"]["vocab"]
    n = len(vocab)
    id_to_token = [None] * n
    for token, index in vocab.items():
        id_to_token[index] = token
    assert all(t is not None for t in id_to_token)
    index = {t: i for i, t in enumerate(id_to_token)}
    merges = tok_json["model"]["merges"]
    added = []
    for item in tok_json.get("added_tokens", []):
        added.append((int(item["id"]), item["content"]))
    bos = int(tok_json.get("post_processor", {}).get("special_tokens", {}).get(
        "<|begin_of_text|>", {}).get("ids", [128000])[0])
    eos = 128001
    for item in tok_json.get("added_tokens", []):
        if item["content"] == "<|end_of_text|>":
            eos = int(item["id"])
    with open(path, "wb") as f:
        f.write(b"M5TK1\0\0\0")
        f.write(struct.pack("<I", n))
        for token in id_to_token:
            raw = token.encode("utf-8")
            f.write(struct.pack("<I", len(raw)))
            f.write(raw)
        f.write(struct.pack("<I", len(merges)))
        for a, b in merges:
            merged = a + b
            f.write(struct.pack("<III", index[a], index[b], index[merged]))
        f.write(struct.pack("<I", len(added)))
        for tid, content in added:
            raw = content.encode("utf-8")
            f.write(struct.pack("<II", tid, len(raw)))
            f.write(raw)
        f.write(struct.pack("<III", bos, eos, 0))
    print(f"tokenizer.bin: {path.stat().st_size/1e6:.1f} MB, vocab {n}, merges {len(merges)}, added {len(added)}")


def split_codec(assets):
    z = np.load(assets / "codec_rvq.npz")
    z2 = np.load(assets / "codec_enc_vq.npz")
    mapping = {
        "dec_sem_book": ("codec_rvq.npz", "book_sem"),
        "dec_rest_book": ("codec_rvq.npz", "book_rest"),
        "dec_proj_sem_w": ("codec_rvq.npz", "proj_sem_w"),
        "dec_proj_sem_b": ("codec_rvq.npz", "proj_sem_b"),
        "dec_proj_rest_w": ("codec_rvq.npz", "proj_rest_w"),
        "dec_proj_rest_b": ("codec_rvq.npz", "proj_rest_b"),
        "enc_sem_book": ("codec_enc_vq.npz", "enc_sem_book"),
        "enc_ac_book": ("codec_enc_vq.npz", "enc_ac_book"),
        "enc_sem_w": ("codec_enc_vq.npz", "enc_sem_w"),
        "enc_ac_w": ("codec_enc_vq.npz", "enc_ac_w"),
    }
    for name, (src, key) in mapping.items():
        np.save(assets / f"{name}.npy", np.ascontiguousarray(z2[key] if src.startswith("codec_enc") else z[key], np.float32))


CPP_HEADER = """// generated by export/export_cpp_assets.py - do not edit
#pragma once
static const int kSeq = {seq};
static const int kCap = {cap};
static const int kDepthSlots = {depth_slots};
static const int kCodecFrames = {codec_frames};
static const int kCodecSamples = {codec_samples};
static const int kCodebooks = {codebooks};
static const int kAudioVocab = {audio_vocab};
static const int kHidden = {hidden};
static const int kBackboneLayers = {backbone_layers};
static const int kBackboneKv = {backbone_kv_heads};
static const int kDecoderLayers = {decoder_layers};
static const int kDecoderKv = {decoder_kv_heads};
static const int kSampleRate = {sample_rate};
static const int kHop = {hop_length};
static const int kTopK = {topk};
static const float kTemperature = {temperature}f;
static const int kMinFrames = {min_frames};
static const int kWindow = {window};
static const int kEos = {eos_token_id};
static const int kCodecLayers = {codec_layers};
static const int kCodecKv = {codec_kv_heads};
static const int kCodecDim = {codec_head_dim};
static const float kBackboneRopeScale = {backbone_rope_scale}f;
static const float kDecoderRopeScale = {decoder_rope_scale}f;
static const float kCodecInvFreq[32] = {codec_inv_freq};
static const float kBackboneInvFreq[32] = {backbone_inv_freq};
static const float kDecoderInvFreq[32] = {decoder_inv_freq};
static const int kCodecStates = {codec_states};
static const int kCodecStateShapes[{codec_states}][3] = {codec_state_shapes};
"""


def write_cpp_header(assets):
    import numpy as np
    cfg = json.loads((assets / "config.json").read_text())
    meta = json.loads((assets / "codec_meta.json").read_text())
    shapes = [s["shape"] for s in meta["codec_states"]]
    def fl(name):
        a = np.load(assets / name)
        return "{" + ",".join(repr(float(x)) + "f" for x in a) + "}"
    text = CPP_HEADER.format(
        codec_layers=meta["codec_layers"], codec_kv_heads=meta["codec_kv_heads"],
        codec_head_dim=meta["codec_head_dim"], codec_states=len(shapes),
        codec_state_shapes="{" + ",".join("{" + ",".join(str(v) for v in s) + "}" for s in shapes) + "}",
        codec_inv_freq=fl("codec_inv_freq.npy"), backbone_inv_freq=fl("backbone_inv_freq.npy"),
        decoder_inv_freq=fl("decoder_inv_freq.npy"), **cfg)
    (ROOT / "sdk" / "cpp" / "src" / "m5_config.h").write_text(text)
    print("wrote sdk/cpp/src/m5_config.h")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "export" / "assets"))
    a = ap.parse_args()
    out = Path(a.out)
    tok = json.loads((out / "tokenizer.json").read_text())
    write_tokenizer(out / "tokenizer.bin", tok)
    split_codec(out)
    write_cpp_header(out)
    print("cpp assets written to", out)


if __name__ == "__main__":
    main()
